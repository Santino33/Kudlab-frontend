// End-to-end synthetic activity, then compare the two teacher journeys to the same student.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { assertPreviewOrigins, compiledOrigins } from './preview-origins.mjs';
const teacherOrigin = process.env.KUDLAB_TEACHER_ORIGIN ?? 'http://localhost:5185';
const apiOrigin = process.env.KUDLAB_API_ORIGIN ?? 'http://localhost:4315';
const playOrigin = process.env.KUDLAB_PLAY_ORIGIN ?? 'http://127.0.0.1:4185';
for (const value of [teacherOrigin, apiOrigin, playOrigin]) assert.match(value, /^http:\/\/(localhost|127\.0\.0\.1):\d+$/);
const [teacherOrigins, playOrigins] = await Promise.all([compiledOrigins(teacherOrigin), compiledOrigins(playOrigin)]);
assertPreviewOrigins(teacherOrigins, playOrigins, { teacherOrigin, apiOrigin, playOrigin });
console.log('PASS: compiled Kudlab and Play use the same API and reciprocal origins');
const { chromium, expect } = await import(process.env.KUDLAB_PLAYWRIGHT ?? '@playwright/test');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const teacherContext = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const publicContext = await browser.newContext();
const teacher = await teacherContext.newPage(), play = await publicContext.newPage();
const errors = [], cookieLeaks = [];
for (const page of [teacher, play]) page.on('pageerror', error => errors.push(error.name));
play.on('request', request => { if (request.url().startsWith(`${apiOrigin}/api/v1/game-runtime/`) && request.headers().cookie) cookieLeaks.push(true); });
const evidence = process.env.KUDLAB_INSPECT_OUTPUT ?? '/tmp/opencode/student-sessions-review';
await mkdir(evidence, { recursive: true });
try {
  await teacher.goto(teacherOrigin);
  await teacher.getByLabel('Correo', { exact: true }).fill('teacher-a@pilot.edu.co');
  await teacher.getByLabel('Contraseña', { exact: true }).fill('TeacherPass1');
  await teacher.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await teacher.getByRole('link', { name: 'Mis cursos', exact: true }).first().click();
  await teacher.locator('.course-card').filter({ has: teacher.getByRole('heading', { name: 'A1', exact: true }) }).getByRole('link', { name: 'Abrir curso', exact: true }).click();
  const groupId = new URL(teacher.url()).pathname.split('/').at(-1);
  const roster = await (await teacher.request.get(`${apiOrigin}/api/v1/groups/${groupId}/students`)).json();
  const student = roster.items.find(s => s.studentCode === 'J02-FICTICIO-A');
  const other = roster.items.find(s => s.studentCode === 'J03-FICTICIO-B');
  assert.ok(student && other, 'Expected synthetic fixture');
  await teacher.getByRole('link', { name: 'Asignaciones de tareas digitales' }).click();
  await teacher.getByRole('button', { name: 'Asignar actividad', exact: true }).click();
  await teacher.getByLabel(/Participante Sintético A/).check();
  const local = ms => teacher.evaluate(ms => { const d = new Date(ms); return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}T${String(d.getHours()).padStart(2,'0')}:${String(d.getMinutes()).padStart(2,'0')}`; }, ms);
  await teacher.getByLabel('Disponible desde').fill(await local(Date.now() - 60000));
  await teacher.getByLabel('Disponible hasta').fill(await local(Date.now() + 3600000));
  await teacher.getByLabel('Máximo de intentos').fill('2');
  const created = teacher.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/task-assignments' && r.request().method() === 'POST' && r.ok());
  await teacher.getByRole('button', { name: 'Guardar asignación y códigos', exact: true }).click();
  const assignment = await (await created).json();
  assert.equal(assignment.recipients[0].studentId, student.id);
  await expect.poll(() => teacher.locator('.access-code-row .classroom-code[data-state="ready"]').count()).toBe(1);
  const code = await teacher.locator('.access-code-row .classroom-code').textContent();
  assert.ok(/^[23456789ABCDEFGHJKLMNPQRSTUVWXYZ]{5}$/.test(code), 'Real code required');
  const assignmentUrl = teacher.url();
  await teacher.getByRole('button', { name: 'Ocultar códigos', exact: true }).click();
  await play.bringToFront(); await play.goto(playOrigin);
  await play.getByLabel('Código de actividad', { exact: true }).fill(code);
  await play.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(play.getByRole('button', { name: 'Comenzar', exact: true })).toBeEnabled();
  await play.getByRole('button', { name: 'Comenzar', exact: true }).click();
  await expect(play.locator('canvas')).toBeVisible();
  console.log('PASS: assignment created in Kudlab and its code accepted by independent Play; waiting for the real 120-second activity');
  await expect(play.getByRole('heading', { name: 'Terminaste la actividad', exact: true })).toBeVisible({ timeout: 135000 });
  let completed;
  await expect.poll(async () => {
    const response = await teacher.request.get(`${apiOrigin}/api/v1/students/${student.id}/task-sessions?limit=25`);
    assert.equal(response.status(), 200);
    completed = (await response.json()).items.find(s => s.assignmentId === assignment.id && s.receivedAt !== null);
    return Boolean(completed && completed.processingStatus === 'COMPLETED');
  }, { timeout: 20000 }).toBe(true);
  assert.equal(completed.executionStatus, 'COMPLETED');
  assert.equal(completed.studentId, student.id);
  assert.deepEqual(cookieLeaks, []);
  console.log('PASS: actual activity completed, evidence received and processed in the same API/DB without teacher cookies');

  await teacher.bringToFront(); await teacher.goto(assignmentUrl);
  await teacher.getByRole('button', { name: 'Gestionar acceso de Participante Sintético A', exact: true }).click();
  const fromAssignment = teacher.waitForResponse(r => new URL(r.url()).pathname === `/api/v1/students/${student.id}/task-sessions`);
  await teacher.getByRole('link', { name: 'Ver sesiones', exact: true }).click();
  const assignmentItems = (await (await fromAssignment).json()).items;
  await expect(teacher.locator(`a[href$="/${completed.id}"]`)).toBeVisible();
  const expectedUrl = `${teacherOrigin}/academico/cursos/${groupId}/estudiantes/${student.id}/tareas`;
  assert.equal(teacher.url(), expectedUrl);
  await teacher.getByRole('link', { name: 'Volver a la ficha', exact: true }).click();
  const fromStudent = teacher.waitForResponse(r => new URL(r.url()).pathname === `/api/v1/students/${student.id}/task-sessions`);
  await teacher.getByRole('link', { name: 'Tareas digitales y sesiones', exact: true }).click();
  const studentItems = (await (await fromStudent).json()).items;
  assert.equal(teacher.url(), expectedUrl);
  assert.deepEqual(studentItems.map(s => s.id), assignmentItems.map(s => s.id));
  await expect(teacher.locator(`a[href$="/${completed.id}"]`)).toBeVisible();
  await expect(teacher.getByText('Sin sesiones en esta página', { exact: true })).toHaveCount(0);
  for (const width of [1440, 768, 390]) {
    await teacher.setViewportSize({ width, height: 950 });
    assert.ok(await teacher.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No general horizontal overflow');
    await teacher.screenshot({ path: `${evidence}/student-sessions-${width}.png`, fullPage: true });
  }
  await teacher.locator(`a[href$="/${completed.id}"]`).click();
  await expect(teacher.getByRole('heading', { name: 'Detalle de sesión', exact: true })).toBeVisible();
  await expect(teacher.getByText('Procesamiento completado', { exact: true })).toBeVisible();
  await teacher.getByRole('link', { name: 'Ver asignación', exact: true }).click();
  assert.equal(teacher.url(), assignmentUrl);
  await teacher.getByRole('button', { name: 'Ocultar códigos', exact: true }).click();
  console.log('PASS: assignment and student profile request the same student, show identical sessions, and open the same persisted detail');

  await teacher.goto(`${teacherOrigin}/academico/cursos/${groupId}/estudiantes/${other.id}/tareas`);
  await expect(teacher.getByRole('heading', { name: 'Tareas digitales', exact: true })).toBeVisible();
  const otherItems = await (await teacher.request.get(`${apiOrigin}/api/v1/students/${other.id}/task-sessions?limit=25`)).json();
  assert.ok(otherItems.items.every(s => s.studentId === other.id && s.id !== completed.id));
  await expect(teacher.locator(`a[href$="/${completed.id}"]`)).toHaveCount(0);
  assert.deepEqual(errors, []);
  console.log('PASS: no cross-student session leakage; no JS errors. Screenshots contain synthetic session data only.');
  console.log(`Verified student history: ${expectedUrl}`);
} finally { await browser.close(); }
